def emit_definitions(methods):
    out = [HEADER]
    out.append("# All quantities are per K of base workforce (size x building_base_employees), not per K actually employed.")
    out.append("# pm_construction_input_amount is the TOTAL per K, spent evenly over pm_construction_duration months.")
    out.append("# pm_industrial_capacity_use is transport demand, pm_industrial_capacity is transport supplied.\n")
    out.append("define_all_production_methods = {")
    out += [f"\tdefine_{t} = yes" for t in methods]
    out.append("}\n")
    for t, m in methods.items():
        out.append(f"define_{t} = {{ # {m.name} ({m.year})" if not getattr(m, "legacy", False) else f"define_{t} = {{ # legacy, not in the sheet yet")
        if m.tech:
            val = "-1" if m.tech == -1 else f"token:{m.tech}"
            out.append(f"\tset_variable = {{ global.pm_tech_unlock@token:{t} = {val} }}")
        if m.output:
            out.append(f"\tset_variable = {{ global.pm_output_amount@token:{t} = {fmt(m.output)} }}")
        if m.transport_out:
            out.append(f"\tset_variable = {{ global.pm_industrial_capacity@token:{t} = {fmt(m.transport_out)} }}")
        if m.shipping:
            out.append(f"\tset_variable = {{ global.pm_shipping_capacity@token:{t} = {fmt(m.shipping)} }}")
        if m.transport_use:
            out.append(f"\tset_variable = {{ global.pm_industrial_capacity_use@token:{t} = {fmt(m.transport_use)} }}")
        if m.duration:
            out.append(f"\tset_variable = {{ global.pm_construction_duration@token:{t} = {fmt(m.duration)} }}")
        for key, rows in (("pm_input", m.inputs), ("pm_construction_input", m.construction)):
            out.append(f"\tclear_array = global.{key}@token:{t}")
            out.append(f"\tclear_array = global.{key}_amount@token:{t}")
            for good, qty in rows:
                out.append(f"\tadd_to_array = {{ global.{key}@token:{t} = token:{good} }}")
                out.append(f"\tadd_to_array = {{ global.{key}_amount@token:{t} = {fmt(qty)} }}")
        if t == "pm_subsistence_farming":
            out.append(f"\tset_variable = {{ global.pm_workforce_peasants@token:{t} = 1 }}")
        else:
            if m.wrk:
                out.append(f"\tset_variable = {{ global.pm_workforce_laborers@token:{t} = {fmt(m.wrk)} }}")
            if m.mid:
                out.append(f"\tset_variable = {{ global.pm_workforce_workers@token:{t} = {fmt(m.mid)} }}")
        out.append("}")
    return "\n".join(out) + "\n"


