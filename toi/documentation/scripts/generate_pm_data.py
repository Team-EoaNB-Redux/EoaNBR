def emit_icons(methods, legacy_data):
    icons = legacy_data["icons"]
    reverse = {new: old for old, new in RENAMES.items()}
    out = [HEADER, "spriteTypes = {"]
    placeholder = []
    for t, m in methods.items():
        if t in icons:
            continue
        old = reverse.get(t)
        texture = icons.get(old)
        if not texture:
            for other in family_members(methods, m.family) if not getattr(m, "legacy", False) else []:
                texture = texture or icons.get(other.token) or icons.get(reverse.get(other.token))
        if not texture:
            texture = icons["pm_no_automation"]
        if not icons.get(old):
            placeholder.append(t)
        out += ["\tspriteType = {", f'\t\tname = "GFX_{t}"', f'\t\ttexturefile = "{texture}"', "\t}"]
    out.append("}")
    return "\n".join(out) + "\n", placeholder


def replace_marked(path, begin, end, body, check):
    text = path.read_text(encoding="utf-8-sig")
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if not pattern.search(text):
        sys.exit(f"{path}: markers '{begin}' not found")
    new = pattern.sub(lambda _: f"{begin}\n{body}{end}", text)
    if not check:
        path.write_text(new, encoding="utf-8")
    print(f"  {'would update' if check else 'updated'} {path.relative_to(TOI)}")


def tech_exists():
    names = set()
    for f in (TOI / "common/technologies").glob("*.txt"):
        names |= set(re.findall(r"^\s*([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig", errors="replace"), re.M))
    return names


def wage_mult(m):
    return (m.wrk or 0) + 2 * (m.mid or 0)


def emit_report(methods, assignments, price, placeholder):
    def pick(key, pred):
        return [m for m in methods.values() if pred(m.sources.get(key, ""))]

    out = ["# PM generation report", "", "Generated by `documentation/scripts/generate_pm_data.py`. Everything here is a default the sheet doesn't supply yet: "
           "add the value to the sheet and it disappears from this list.", ""]
    rows = [m for m in methods.values() if not getattr(m, "legacy", False)]
    out += [f"- Sheet methods: {len(rows)}. Legacy methods kept from the old file: {len(methods) - len(rows)}.", ""]

    out += ["## Workforce filled in", "", "| Method | Family | Wrk | Mid | Source |", "|---|---|---:|---:|---|"]
    for m in pick("workforce", lambda s: s not in ("sheet", "legacy")):
        out.append(f"| {m.name} | {m.family} | {fmt(m.wrk)} | {fmt(m.mid)} | {m.sources['workforce']} |")

    out += ["", "## Construction filled in from era baskets", "", "| Method | Basket | $ per K at base price |", "|---|---|---:|"]
    for m in pick("construction", lambda s: s.endswith("basket")):
        out.append(f"| {m.name} | {m.sources['construction']} | {sum(q * price[g] for g, q in m.construction):.2f} |")

    out += ["", "## Durations not in the sheet", "", "| Method | Months | Source |", "|---|---:|---|"]
    for m in pick("duration", lambda s: s not in ("sheet", "legacy")):
        out.append(f"| {m.name} | {fmt(m.duration)} | {m.sources['duration']} |")

    out += ["", "## Methods with no tech (never unlocked)", ""]
    out += [f"- {m.name} ({m.year})" for m in methods.values() if m.tech == -1]

    known = tech_exists()
    missing = sorted({m.tech for m in methods.values() if isinstance(m.tech, str) and m.tech not in known})
    out += ["", "## Tech names that don't exist", ""] + ([f"- `{t}`" for t in missing] or ["None."])

    out += ["", "## Negative value add", "", "At base prices for the PM's year. Excludes transport inputs, which industries no longer pay for.", "",
            "| Method | Year | Revenue | Inputs | VA |", "|---|---:|---:|---:|---:|"]
    for m in rows:
        if m.kind == "pm" and m.sheet_revenue and m.sheet_revenue < m.sheet_inputs:
            out.append(f"| {m.name} | {m.year} | {m.sheet_revenue:.2f} | {m.sheet_inputs:.2f} | {m.sheet_revenue - m.sheet_inputs:.2f} |")

    out += ["", "## PM + AM combinations where a tier clamps at 0", "",
            "The sheet's AM deltas are additive. Jobs can't go negative, so these combinations employ more than the ROI tab assumes.", "",
            "| Building | PM | AM | Wrk | Mid |", "|---|---|---|---:|---:|"]
    seen = set()
    for b, pms, ams, *_ in assignments:
        for p in pms:
            for a in ams:
                key = (p, a)
                if key in seen:
                    continue
                seen.add(key)
                pm, am = methods[p], methods[a]
                w, d = (pm.wrk or 0) + (am.wrk or 0), (pm.mid or 0) + (am.mid or 0)
                if w < -1e-9 or d < -1e-9:
                    out.append(f"| {b} | {pm.name} | {am.name} | {fmt(w)} | {fmt(d)} |")

    out += ["", "## Icons using placeholder art", ""] + [f"- {t}" for t in placeholder]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only")
    check = ap.parse_args().check

    methods, legacy_data = load_methods()
    assignments, price = resolve_assignments(methods)

    # The sheet's own values at each PM's year, for the report. Transport isn't an expense any more.
    pg = load_sheet(WORKBOOK, "PM_Goods")
    for m in methods.values():
        m.sheet_revenue = m.sheet_inputs = 0.0
    for r, row in pg.items():
        if r > 1 and row.get("A"):
            m = methods[tokenize(row["A"])]
            value = float(row.get("G", 0) or 0)
            if row.get("C") == "output":
                m.sheet_revenue += value
            elif row.get("C") == "input" and row.get("D") != "transport":
                m.sheet_inputs += value

    no_duration = [t for t, m in methods.items() if m.construction and not m.duration]
    if no_duration:
        sys.exit(f"Methods with a construction list but no duration: {no_duration}")

    assigned = {t for _, pms, ams, *_ in assignments for t in pms + ams}
    unassigned = [t for t in methods if t not in assigned]
    if unassigned:
        sys.exit(f"Methods not on any building: {unassigned}")
    undefined = sorted(t for t in assigned if t not in methods)
    if undefined:
        sys.exit(f"Buildings reference undefined methods: {undefined}")

    write(TOI / "common/scripted_effects/_economy_definitions_pms.txt", emit_definitions(methods), check)
    write(TOI / "common/scripted_effects/_economy_definitions_pm_assignments.txt", emit_assignments(assignments), check)
    write(TOI / "common/scripted_effects/_economy_pm_modifier_factors.txt", emit_factors(methods), check)
    write(TOI / "common/modifier_definitions/01_economy_pm_modifiers.txt", emit_modifiers(methods), check)
    write(TOI / "localisation/english/economy_pms_l_english.yml", emit_localisation(methods), check)
    icons, placeholder = emit_icons(methods, legacy_data)
    write(TOI / "interface/economy_pm_icons.gfx", icons, check)
    write(TOI / "documentation/Planning/pm_generation_report.md", emit_report(methods, assignments, price, placeholder), check)

    tokens = "".join(f"\t{t}\n" for t in methods)
    mods = "".join(f"\t{t}_throughput_modifier\n\t{t}_employment_modifier\n" for t in methods)
    replace_marked(TOI / "common/synchronized_dynamic_tokens/eoanbr_tokens.txt", "# BEGIN GENERATED PM TOKENS", "# END GENERATED PM TOKENS", tokens, check)
    replace_marked(TOI / "common/synchronized_dynamic_tokens/eoanbr_tokens.txt", "# BEGIN GENERATED PM MODIFIERS", "# END GENERATED PM MODIFIERS", mods, check)
    enums = "".join(f"\t\t\t{t}\n" for t in methods)
    replace_marked(TOI / "common/script_enums.txt", "# BEGIN GENERATED PM TOKENS 1", "# END GENERATED PM TOKENS 1", enums, check)
    replace_marked(TOI / "common/script_enums.txt", "# BEGIN GENERATED PM TOKENS 2", "# END GENERATED PM TOKENS 2", enums, check)
    print(f"{len(methods)} methods, {len(assignments)} buildings")


if __name__ == "__main__":
    main()
