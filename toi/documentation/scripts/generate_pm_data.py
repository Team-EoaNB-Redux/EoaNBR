def fmt(x):
    s = f"{x:.5f}".rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s


def load_sheet(path, name):
    """Returns {row: {column: value}} for one tab, using cached cell values (formulas are not evaluated here)."""
    M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
    R = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"
    with zipfile.ZipFile(path) as z:
        wb = ET.fromstring(z.read("xl/workbook.xml"))
        rels = {r.get("Id"): r.get("Target") for r in ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))}
        strings = ["".join(t.text or "" for t in si.iter(M + "t")) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(M + "si")]
        for s in wb.find(M + "sheets"):
            if s.get("name") != name:
                continue
            target = rels[s.get(R + "id")].lstrip("/")
            target = target if target.startswith("xl/") else "xl/" + target
            rows = collections.defaultdict(dict)
            for c in ET.fromstring(z.read(target)).iter(M + "c"):
                v = c.find(M + "v")
                if v is None:
                    continue
                val = strings[int(v.text)] if c.get("t") == "s" else v.text
                ref = c.get("r")
                col = re.match("[A-Z]+", ref).group(0)
                rows[int(ref[len(col):])][col] = val
            return rows
    raise KeyError(name)


class Method:
    def __init__(self, token, name, kind, family):
        self.token, self.name, self.kind, self.family = token, name, kind, family
        self.year = 1857
        self.output = 0.0
        self.inputs = []
        self.construction = []
        self.transport_use = 0.0
        self.transport_out = 0.0
        self.shipping = 0.0
        self.duration = 0
        self.wrk = None
        self.mid = None
        self.tech = 0            # 0 = always, -1 = never, else a tech name
        self.sources = {}
        self.first_in_family = False


def tokenize(name):
    fixed = NAME_FIXES.get(name, name).lower().replace("-", " ")
    return "pm_" + re.sub(r" +", "_", re.sub(r"[^a-z0-9 ]", "", fixed).strip())


def load_methods():
    pg, pm_sheet = load_sheet(WORKBOOK, "PM_Goods"), load_sheet(WORKBOOK, "PMs")
    legacy_data = json.loads(LEGACY_JSON.read_text(encoding="utf-8"))
    families = {**PM_FAMILIES, **AM_FAMILIES}
    family_of = {n: f for f, names in families.items() for n in names}
    methods = collections.OrderedDict()

    for r in sorted(pg):
        row = pg[r]
        if r == 1 or not row.get("A"):
            continue
        name = row["A"]
        if name not in family_of:
            sys.exit(f"PM_Goods row {r}: '{name}' isn't in a family (add it to PM_FAMILIES / AM_FAMILIES)")
        tok = tokenize(name)
        fam = family_of[name]
        m = methods.setdefault(tok, Method(tok, NAME_FIXES.get(name, name), "am" if fam in AM_FAMILIES else "pm", fam))
        m.year = int(float(row.get("B", 1857)))
        qty = float(row.get("E", 0) or 0)
        kind, good = row.get("C"), row.get("D")
        if qty == 0:
            continue
        if kind == "output":
            if good == "transport":
                m.transport_out = qty
            elif good == "shipping":
                m.shipping = qty
            elif m.output == 0:
                m.output = qty                 # further outputs are the building's job (subsistence wood/fiber)
        elif kind == "input":
            if good == "transport":
                m.transport_use = qty
            else:
                m.inputs.append((good, qty))
        elif kind == "construction":
            m.construction.append((good, qty))
    for name in family_of:
        if tokenize(name) not in methods:
            sys.exit(f"'{name}' is in a family but not in PM_Goods")

    for fam, names in families.items():
        methods[tokenize(names[0])].first_in_family = True

    sheet_rows = {tokenize(pm_sheet[r]["A"]): pm_sheet[r] for r in sorted(pm_sheet, reverse=True) if r > 1 and pm_sheet[r].get("A")}
    for tok, m in methods.items():
        row = sheet_rows.get(tok, {})
        if row.get("G") is not None or row.get("H") is not None:
            m.wrk, m.mid = float(row.get("G", 0) or 0), float(row.get("H", 0) or 0)
            m.sources["workforce"] = "sheet"
        m.sheet_duration = float(row["O"]) if row.get("O") else 0
        m.sheet_tech = row.get("C")

    fill_workforce(methods)
    fill_construction(methods, legacy_data)
    fill_tech(methods, legacy_data)
    add_legacy(methods, legacy_data)
    return methods, legacy_data


def family_members(methods, fam):
    names = {**PM_FAMILIES, **AM_FAMILIES}[fam]
    return [methods[tokenize(n)] for n in names]


def fill_workforce(methods):
    def interpolate(members):
        known = [i for i, m in enumerate(members) if m.wrk is not None]
        if not known:
            return False
        for i, m in enumerate(members):
            if m.wrk is not None:
                continue
            lo = max((k for k in known if k < i), default=None)
            hi = min((k for k in known if k > i), default=None)
            if lo is None:
                a, b, t = members[hi], members[hi], 0
            elif hi is None:
                a, b, t = members[lo], members[lo], 0
            else:
                a, b, t = members[lo], members[hi], (i - lo) / (hi - lo)
            m.wrk = a.wrk + (b.wrk - a.wrk) * t
            m.mid = a.mid + (b.mid - a.mid) * t
            m.sources["workforce"] = f"interpolated from {a.name}" + (f" / {b.name}" if a is not b else "")
        return True

    pending = []
    for fam in {**PM_FAMILIES, **AM_FAMILIES}:
        members = family_members(methods, fam)
        if fam in AM_FAMILIES:
            if fam not in TIER_ANALOG and not interpolate(members):
                sys.exit(f"AM family {fam} has no workforce data")
            continue
        # Base-tier PMs with nothing authored are plain labor: 100% Wrk.
        if members[0].wrk is None and members[0].year == 1857:
            members[0].wrk, members[0].mid = 1.0, 0.0
            members[0].sources["workforce"] = "default for a family's first PM"
        if sum(1 for m in members if m.sources.get("workforce") == "sheet") == 0:
            pending.append(fam)
            continue
        interpolate(members)

    for fam, analog in TIER_ANALOG.items():
        rows = family_members(methods, analog)
        for i, m in enumerate(family_members(methods, fam)):
            src = rows[min(i, len(rows) - 1)]
            if m.wrk is None:
                m.wrk, m.mid = src.wrk, src.mid
                m.sources["workforce"] = f"copied from {src.name}"

    for fam in pending:
        analog = LAND_ANALOG if fam in LAND_FAMILIES else FACTORY_ANALOG
        rows = family_members(methods, analog)
        seen = collections.Counter()
        for m in family_members(methods, fam):
            same = [r for r in rows if r.year == m.year] or [max((r for r in rows if r.year <= m.year), key=lambda r: r.year, default=rows[0])]
            src = same[min(seen[m.year], len(same) - 1)]
            seen[m.year] += 1
            if m.wrk is None:
                m.wrk, m.mid = src.wrk, src.mid
                m.sources["workforce"] = f"copied from {src.name}"


def fill_construction(methods, legacy_data):
    reverse = {new: old for old, new in RENAMES.items()}
    durations = legacy_data["old_duration"]
    for tok, m in methods.items():
        old = reverse.get(tok, tok if tok in durations else None)
        if m.sheet_duration:
            m.duration = m.sheet_duration
            m.sources["duration"] = "sheet"
        elif old and durations.get(old):
            m.duration = durations[old]
            m.sources["duration"] = f"old {old}"
        else:
            m.duration = (ERA_DURATION_AM if m.kind == "am" else ERA_DURATION_PM)[m.year]
            m.sources["duration"] = "era default"

        if m.construction:
            m.sources["construction"] = "sheet"
            continue
        if m.family == "subsistence":
            m.sources["construction"] = "none (not buildable)"
            continue
        input_of = dict(m.inputs)
        if m.year == 1857:
            era = "1800" if m.first_in_family and "machinery" not in input_of else "1850"
        else:
            era = str(m.year)
        fixed, scaled = BASKETS[era]
        m.construction = [(g, float(q)) for g, q in fixed.items()]
        if scaled:
            for good, driver, factor in BASKET_SCALING:
                if input_of.get(driver):
                    m.construction.append((good, input_of[driver] * factor))
        m.sources["construction"] = f"{era} basket"


def fill_tech(methods, legacy_data):
    reverse = {new: old for old, new in RENAMES.items()}
    old_tech = legacy_data["old_tech"]
    for tok, m in methods.items():
        sheet = m.sheet_tech
        if tok in TECH_OVERRIDES:
            m.tech = TECH_OVERRIDES[tok]
            m.sources["tech"] = "never (override)"
            continue
        if sheet:
            m.tech = {"always": 0, "never": -1}.get(sheet, SHEET_TECH_ALIASES.get(sheet, sheet))
            m.sources["tech"] = "sheet"
            continue
        old = reverse.get(tok)
        if old is None and tok in old_tech and tok not in RENAMES:
            old = tok
        if old is not None and old_tech.get(old):
            m.tech = int(old_tech[old]) if old_tech[old].lstrip("-").isdigit() else old_tech[old]
            m.sources["tech"] = f"old {old}"
        elif (old is not None and old in old_tech) or m.first_in_family:
            m.tech = 0
            m.sources["tech"] = "always (base tier)"
        else:
            m.tech = -1
            m.sources["tech"] = "never (no tech assigned)"


def add_legacy(methods, legacy_data):
    old_tech = legacy_data["old_tech"]
    for tok, d in legacy_data["legacy"].items():
        m = Method(tok, tok[3:].replace("_", " ").title(), d["kind"], d["family"])
        m.output, m.transport_use, m.duration = d["output"], d["transport_use"], d["duration"]
        m.inputs = [tuple(i) for i in d["inputs"]]
        m.construction = [tuple(i) for i in d["construction"]]
        m.wrk, m.mid = d["laborers"], d["workers"]
        tech = old_tech.get(tok)
        m.tech = (int(tech) if tech and tech.lstrip("-").isdigit() else tech) or 0
        m.legacy = True
        m.sources = {"workforce": "legacy", "construction": "legacy", "duration": "legacy", "tech": "legacy"}
        methods[tok] = m


def resolve_assignments(methods):
    """Returns [(building, [pm tokens], [am tokens], [multipliers] or None)]."""
    goods = load_sheet(WORKBOOK, "Goods")
    price = {goods[r]["A"]: float(goods[r]["C"]) for r in goods if r > 1 and goods[r].get("A") and goods[r].get("C") and goods[r]["A"] != "Target"}

    def expand(entries):
        out = []
        for e in entries:
            out += [m.token for m in family_members(methods, e)] if e in {**PM_FAMILIES, **AM_FAMILIES} else [e]
        return out

    result = []
    for buildings, pms, ams in ASSIGNMENTS:
        for b in buildings:
            family = pms[0]
            mult, amounts = 1, [1]
            if b in OUTPUT_AMOUNTS:
                amounts = OUTPUT_AMOUNTS[b]
            elif family in PARITY_REFERENCE:
                mult = price[PARITY_REFERENCE[family]] / price[PARITY_GOOD[b]]
            elif family.startswith("pm_") and methods[family].family == "govt":
                amounts = []
            result.append((b, expand(pms), expand(ams), mult, amounts))
    return result, price


